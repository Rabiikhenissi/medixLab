    <h2 class="text-base font-bold text-[#1e293b]">2. Données collectées</h2>
    <p>
        Nous collectons les données strictement nécessaires à votre prise en charge : identité, coordonnées,
        et — pour les patients — les informations de santé partagées par vous ou vos professionnels de santé.
        Nous enregistrons également des journaux techniques (adresse IP, navigateur) pour la sécurité.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">3. Bases légales</h2>
    <p>
        Vos données sont traitées sur la base de : votre <strong>consentement</strong> explicite (enregistré
        lors de l'inscription), l'<strong>exécution de votre contrat</strong> de prise en charge, et notre
        <strong>obligation légale</strong> de conservation de certaines données de santé.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">4. Durée de conservation</h2>
    <p>
        Les données de santé sont conservées pendant la durée légale applicable à la conservation des données
        médicales, puis supprimées ou anonymisées. Les journaux d'audit sont conservés à des fins de traçabilité.
        Vous pouvez demander l'effacement anticipé de votre compte à tout moment.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">5. Partage des données</h2>
    <p>
        Vos données ne sont partagées qu'avec les professionnels de santé et laboratoires que vous avez
        autorisés, et jamais à des fins commerciales. Elles peuvent être transmises aux autorités compétentes
        lorsqu'une obligation légale l'impose.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">6. Vos droits</h2>
    <p>
        Conformément au RGPD, vous disposez des droits d'<strong>accès</strong>, de
        <strong>rectification</strong>, d'<strong>effacement</strong> (droit à l'oubli), de
        <strong>portabilité</strong>, d'<strong>opposition</strong> et de
        <strong>limitation</strong> du traitement. Vous pouvez également retirer votre consentement à tout
        moment. Pour exercer vos droits, contactez-nous à l'adresse ci-dessus ou via votre espace.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">7. Sécurité</h2>
    <p>
        Nous mettons en œuvre des mesures techniques et organisationnelles appropriées : chiffrement des
        mots de passe, authentification à deux facteurs, journalisation des accès et contrôles d'accès
        par rôle et permission.
    </p>

    <h2 class="text-base font-bold text-[#1e293b]">8. Notifications de violation</h2>
    <p>
        En cas de violation de données susceptible d'engendrer un risque pour vos droits et libertés, nous
        vous en informerons ainsi que l'autorité de contrôle compétente, dans les délais prévus par la loi.
    </p>
